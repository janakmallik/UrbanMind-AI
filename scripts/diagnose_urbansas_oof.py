"""Audit the OOF prediction pipeline for Week 9c fusion.

Internal consistency audit — NOT a provenance audit. Verifies that the two
OOF CSVs are internally consistent and structurally valid. Does NOT verify
that each prediction was generated by a model that excluded that clip;
that would require per-fold MLflow runs or reproduction, neither done here.

Pass/fail checks (structural integrity):
    1. Filename sets identical between audio and video
    2. y_true values match
    3. 540 rows, all MAVD subset, no TAU contamination
    4. No duplicate filenames
    5. All filenames map to known locations
    6. Per-fold positive counts match known location distributions

Diagnostic output (printed, not asserted):
    - Probability distribution statistics for both files
    - Per-fold F1 computed from CSV (compare manually to model cards)
    - Pooled ROC-AUC / PR-AUC (compare manually to model cards)

Explicitly noted as unverified:
    - OOF provenance (which run produced which prediction)
    - Actual data used by the pilot (declared split only)

Delete after use.
"""

import sys
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO_ROOT / "src"))

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, f1_score, roc_auc_score

from urbanintel.config import urbansas_root

RESULTS = _REPO_ROOT / "data" / "urbansas_results"

# Fold order ASSUMED from scripts/train_urbansas_audio.py lines 207 + 225:
#   mavd_locations = sorted(mavd_df["location_id"].unique())
#   for fold_idx, test_loc in enumerate(mavd_locations, 1):
# This is the fold numbering used by the training loop. It is NOT independently
# verified against the executed run's logs — see "unverified" section at end.
FOLD_ORDER = ["acevedo0103", "magallanes0308", "rivera0922", "rivera0923", "templete0103"]
FOLD_TO_LOC = {i + 1: loc for i, loc in enumerate(FOLD_ORDER)}

checks = []


def check(name, cond, msg=""):
    checks.append({"name": name, "pass": bool(cond), "msg": msg})
    status = "PASS" if cond else "FAIL"
    print(f"[{status}] {name}" + (f"  — {msg}" if msg else ""))


def diagnose(name, values):
    v = np.asarray(values)
    print(f"[DIAG] {name}:")
    print(f"       count={len(v)}  mean={v.mean():.4f}  std={v.std():.4f}")
    print(
        f"       min={v.min():.4f}  q25={np.percentile(v, 25):.4f}  median={np.median(v):.4f}  q75={np.percentile(v, 75):.4f}  max={v.max():.4f}"
    )


def main():
    print("=" * 72)
    print("OOF PIPELINE AUDIT (internal consistency)")
    print("=" * 72)
    print()

    a = pd.read_csv(RESULTS / "audio_only_oof.csv")
    v = pd.read_csv(RESULTS / "urbansas_video_oof.csv")

    print(f"Audio OOF: {len(a)} rows, cols = {a.columns.tolist()}")
    print(f"Video OOF: {len(v)} rows, cols = {v.columns.tolist()}")
    print()

    # --- Structural checks (pass/fail) ---
    a_set = set(a["filename"])
    v_set = set(v["filename"])
    check(
        "Filename sets identical",
        a_set == v_set,
        f"{len(a_set - v_set)} audio-only, {len(v_set - a_set)} video-only",
    )

    check("Audio has no duplicate filenames", a["filename"].is_unique)
    check("Video has no duplicate filenames", v["filename"].is_unique)

    merged = a.merge(v, on="filename", suffixes=("_a", "_v"), validate="one_to_one")
    check(
        "y_true values match",
        (merged["y_true_a"] == merged["y_true_v"]).all(),
        f"{(merged['y_true_a'] != merged['y_true_v']).sum()} mismatches",
    )

    check("Exactly 540 rows", len(a) == 540 and len(v) == 540, f"audio {len(a)}, video {len(v)}")

    # Attach location from metadata
    root = urbansas_root()
    video_ann = pd.read_csv(root / "annotations" / "video_annotations.csv")
    meta = video_ann.drop_duplicates("filename")[["filename", "location_id", "subset"]].copy()
    merged = merged.merge(meta, on="filename", how="left")

    check(
        "All clips found in metadata",
        merged["location_id"].notna().all(),
        f"{merged['location_id'].isna().sum()} unmapped filenames",
    )

    check(
        "All clips are MAVD subset",
        (merged["subset"] == "mavd").all(),
        f"{len(merged[merged['subset'] != 'mavd'])} non-MAVD rows",
    )

    merged["fold"] = merged["location_id"].apply(
        lambda loc: next((f for f, l in FOLD_TO_LOC.items() if l == loc), None)
    )
    check(
        "All clips map to a known fold",
        merged["fold"].notna().all(),
        f"{merged['fold'].isna().sum()} unmapped locations",
    )

    # Per-fold positive counts vs known expected values
    expected_pos = {
        "acevedo0103": 32,
        "magallanes0308": 48,
        "rivera0922": 2,
        "rivera0923": 28,
        "templete0103": 28,
    }
    print()
    print("Per-fold distribution (ASSUMED fold numbering from code):")
    fold_ok = True
    for fold, loc in FOLD_TO_LOC.items():
        n = (merged["fold"] == fold).sum()
        pos = int(merged.loc[merged["fold"] == fold, "y_true_a"].sum())
        exp = expected_pos[loc]
        match = pos == exp
        if not match:
            fold_ok = False
        mark = "OK" if match else "MISMATCH"
        print(
            f"  fold {fold}: {loc:20s}  {n:3d} clips, {pos:3d} positives (expected {exp})  {mark}"
        )
    check("Per-fold positive counts match known distribution", fold_ok)

    # --- Diagnostics (not asserted) ---
    print()
    print("=" * 72)
    print("DIAGNOSTIC OUTPUT (not pass/fail — for manual review)")
    print("=" * 72)
    diagnose("audio y_prob", a["y_prob"].values)
    print()
    diagnose("video y_prob", v["y_prob"].values)
    print()

    print("Per-fold F1 computed from CSV (compare to model cards manually):")
    print(f"  {'fold':6s} {'location':22s} {'audio_F1':>10s} {'video_F1':>10s}")
    for fold in range(1, 6):
        sub = merged[merged["fold"] == fold]
        pred_a = (sub["y_prob_a"] >= 0.5).astype(int)
        pred_v = (sub["y_prob_v"] >= 0.5).astype(int)
        f1_a = f1_score(sub["y_true_a"], pred_a, zero_division=0)
        f1_v = f1_score(sub["y_true_v"], pred_v, zero_division=0)
        print(f"  {fold:<6d} {FOLD_TO_LOC[fold]:22s} {f1_a:>10.4f} {f1_v:>10.4f}")
    print()

    a_auc = roc_auc_score(merged["y_true_a"], merged["y_prob_a"])
    v_auc = roc_auc_score(merged["y_true_v"], merged["y_prob_v"])
    a_pr = average_precision_score(merged["y_true_a"], merged["y_prob_a"])
    v_pr = average_precision_score(merged["y_true_v"], merged["y_prob_v"])
    print(f"Pooled ROC-AUC audio: {a_auc:.4f}   video: {v_auc:.4f}")
    print(f"Pooled PR-AUC  audio: {a_pr:.4f}   video: {v_pr:.4f}")
    print()
    print("Compare to published values (from model cards):")
    print("  audio: ROC-AUC 0.6237, PR-AUC 0.3296")
    print("  video: ROC-AUC 0.6130, PR-AUC 0.3063")
    print()

    # --- Summary ---
    print("=" * 72)
    passed = sum(c["pass"] for c in checks)
    total = len(checks)
    print(f"SUMMARY: {passed}/{total} structural checks passed")
    print("=" * 72)
    if passed < total:
        print()
        print("FAILED CHECKS:")
        for c in checks:
            if not c["pass"]:
                print(f"  - {c['name']}: {c['msg']}")
        sys.exit(1)

    # --- What this audit does NOT verify ---
    print()
    print("=" * 72)
    print("WHAT THIS AUDIT DOES NOT VERIFY")
    print("=" * 72)
    print("1. OOF provenance: which training run produced each prediction.")
    print("   Verified only by reading train_urbansas_*.py source, not by")
    print("   inspecting MLflow logs (no per-fold MLflow runs exist).")
    print("2. The pilot's actual data: audit only checks the declared split.")
    print("   Does not verify which clips the training functions actually saw.")
    print("3. That the published model card numbers were derived from THESE CSVs")
    print("   and not from a different run. Only manual comparison can confirm.")
    print()
    print("Structural consistency is NOT the same as correctness.")
    print("A consistent pipeline can still produce wrong results.")


if __name__ == "__main__":
    main()
